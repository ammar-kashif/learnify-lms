#!/usr/bin/env node
/**
 * Dumps the live Supabase `public` schema to .claude/supabase-schema.md
 *
 *   npm run schema:dump
 *
 * Reads NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY from .env / .env.local
 * and introspects the PostgREST OpenAPI endpoint (`GET /rest/v1/`), which returns
 * every exposed table with its real column names, types, nullability, defaults and
 * PK/FK relationships. No extra dependencies, no Docker, no DB password.
 *
 * Run this whenever the schema changes so Claude (and you) always work from the
 * actual column names instead of guessing.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = resolve(ROOT, '.claude/supabase-schema.md');

/** Minimal .env parser — avoids pulling in a dependency. */
function loadEnv() {
  const env = { ...process.env };
  for (const name of ['.env', '.env.local']) {
    const path = resolve(ROOT, name);
    if (!existsSync(path)) continue;
    for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
      const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
      if (!match) continue;
      const value = match[2].trim().replace(/^["'](.*)["']$/, '$1');
      if (value) env[match[1]] = value;
    }
  }
  return env;
}

const env = loadEnv();
const url = env.NEXT_PUBLIC_SUPABASE_URL;
const key = env.SUPABASE_SERVICE_ROLE_KEY || env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

if (!url || !key) {
  console.error(
    'Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env'
  );
  process.exit(1);
}

const response = await fetch(`${url.replace(/\/$/, '')}/rest/v1/`, {
  headers: { apikey: key, Authorization: `Bearer ${key}` },
});

if (!response.ok) {
  console.error(`Supabase returned ${response.status} ${response.statusText}`);
  process.exit(1);
}

const spec = await response.json();
const definitions = spec.definitions ?? {};
const tableNames = Object.keys(definitions).sort();

if (tableNames.length === 0) {
  console.error('No tables returned. Check that the key has access to `public`.');
  process.exit(1);
}

/**
 * PostgREST encodes metadata in the column description, e.g.
 *   "Note:\nThis is a Primary Key.<pk/>"
 *   "Note:\nThis is a Foreign Key to `courses.id`.<fk table='courses' column='id'/>"
 */
function readNotes(property) {
  const description = property.description ?? '';
  const notes = [];
  if (description.includes('<pk/>')) notes.push('**PK**');
  const fk = /<fk table='([^']+)' column='([^']+)'\/>/.exec(description);
  if (fk) notes.push(`FK → \`${fk[1]}.${fk[2]}\``);
  const comment = description.split('Note:')[0].trim();
  if (comment) notes.push(comment.replace(/\s+/g, ' '));
  return notes.join(' ');
}

function readType(property) {
  if (Array.isArray(property.enum)) {
    return `enum(${property.enum.map((v) => `'${v}'`).join(' \\| ')})`;
  }
  const base = property.format || property.type || 'unknown';
  return property.type === 'array' ? `${base}[]` : base;
}

const lines = [
  '# Supabase schema — `public`',
  '',
  '> Auto-generated by `npm run schema:dump`. Do not hand-edit; re-run after any migration.',
  `> Source: PostgREST OpenAPI introspection. Tables: ${tableNames.length}.`,
  '',
  '## Tables',
  '',
  tableNames.map((t) => `\`${t}\``).join(' · '),
  '',
];

for (const table of tableNames) {
  const definition = definitions[table];
  const properties = definition.properties ?? {};
  const required = new Set(definition.required ?? []);

  lines.push(`## \`${table}\``, '');
  lines.push('| Column | Type | Nullable | Default | Notes |');
  lines.push('| --- | --- | --- | --- | --- |');

  for (const [column, property] of Object.entries(properties)) {
    const nullable = required.has(column) ? 'NO' : 'YES';
    const fallback =
      property.default === undefined ? '' : `\`${String(property.default)}\``;
    lines.push(
      `| \`${column}\` | ${readType(property)} | ${nullable} | ${fallback} | ${readNotes(property)} |`
    );
  }
  lines.push('');
}

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');

console.log(`Wrote ${tableNames.length} tables to .claude/supabase-schema.md`);
console.log(tableNames.join(', '));
